<h2 id="foundation">Start with visual design fundamentals</h2>
<p>Graphic Design is not only about learning software. Beginners benefit from first understanding layout, spacing, alignment, colour, typography, visual hierarchy and how design communicates a clear message.</p>
<p>Once these foundations are clear, students can use design tools more effectively and create work that looks consistent across posters, social media creatives, brochures, presentations and digital campaigns.</p>

