    <li><strong>Adobe Illustrator</strong> for vector graphics, icons, logos and scalable artwork.</li>
    <li><strong>Canva</strong> for quick layouts, social media posts and reusable brand templates.</li>
    <li><strong>Typography and colour systems</strong> for stronger visual consistency.</li>
    <li><strong>Branding basics</strong> for logo usage, visual identity and brand communication.</li>
    <li><strong>Social media design</strong> for posts, ads, stories, thumbnails and campaign creatives.</li>
    <li><strong>Print design basics</strong> for brochures, flyers and other marketing materials.</li>
</ul>

