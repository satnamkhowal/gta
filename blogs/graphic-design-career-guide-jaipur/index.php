<h2 id="faq">Frequently asked questions</h2>
<h3>Can a beginner learn Graphic Design without drawing skills?</h3>
<p>Yes. Drawing can be useful for some creative work, but beginners can build strong design skills through layout, typography, colour, image editing and digital design practice.</p>

<h3>Which software should I learn first?</h3>
<p>Photoshop is a practical starting point for image-based design, while Illustrator is useful for vectors and logos. Canva can also help beginners practise layout and social media design quickly.</p>

<h3>What should a beginner portfolio include?</h3>
<p>A useful beginner portfolio can include branding, social media creatives, a brochure or poster, a thumbnail or banner set and one complete campaign-style project.</p>

<h3>Can Graphic Design work with Digital Marketing?</h3>
<p>Yes. Digital campaigns regularly need social media posts, ad creatives, landing-page graphics, thumbnails and other visual assets, so design skills pair naturally with digital marketing.</p>
