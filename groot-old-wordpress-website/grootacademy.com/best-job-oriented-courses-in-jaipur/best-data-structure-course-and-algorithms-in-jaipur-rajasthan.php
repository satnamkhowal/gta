                                                            <strong>Q1: What are greedy algorithms?</strong>
                                                            <p>A1: Greedy algorithms make a series of choices, each of
                                                                which looks best at the moment, to find an optimal
                                                                solution.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: How do greedy algorithms work?</strong>
                                                            <p>A2: Greedy algorithms build up a solution piece by piece,
                                                                always choosing the next piece that offers the most
                                                                immediate benefit.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What are the characteristics of greedy
                                                                algorithms?</strong>
                                                            <p>A3: Characteristics include local optimization,
                                                                simplicity, and efficiency, but they may not always
                                                                provide the global optimal solution.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: What are some common problems solved using
                                                                greedy algorithms?</strong>
                                                            <p>A4: Common problems include the activity selection
                                                                problem, Huffman coding, and Dijkstra's algorithm for
                                                                shortest paths.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What is the activity selection problem?</strong>
                                                            <p>A5: The activity selection problem involves selecting the
                                                                maximum number of non-overlapping activities from a
                                                                given set.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: How is Huffman coding used in greedy
                                                                algorithms?</strong>
                                                            <p>A6: Huffman coding is used to compress data by creating a
                                                                binary tree with the shortest codes assigned to the most
                                                                frequent characters.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: How does Dijkstra's algorithm work?</strong>
                                                            <p>A7: Dijkstra's algorithm finds the shortest path from a
                                                                source node to all other nodes in a weighted graph by
                                                                iteratively selecting the node with the minimum
                                                                distance.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: What are the limitations of greedy
                                                                algorithms?</strong>
                                                            <p>A8: Limitations include the possibility of missing the
                                                                global optimum solution and not being suitable for all
                                                                problems, especially those requiring backtracking.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: How do you determine if a problem can be solved
                                                                with a greedy algorithm?</strong>
                                                            <p>A9: A problem can be solved with a greedy algorithm if it
                                                                exhibits the properties of optimal substructure and the
                                                                greedy choice property.</p>
                                                        </div>
