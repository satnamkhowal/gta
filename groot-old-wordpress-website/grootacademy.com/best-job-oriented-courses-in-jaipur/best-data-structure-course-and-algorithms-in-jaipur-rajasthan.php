                                            <div id="collapseEleven" class="collapse show"
                                                aria-labelledby="headingEleven" data-parent="#accordion">
                                                <div class="card-body acc-content current">
                                                    <div class="container">
                                                        <div class="row">
                                                            <strong>Q1: What are backtracking algorithms?</strong>
                                                            <p>A1: Backtracking algorithms solve problems by
                                                                incrementally building a solution and abandoning partial
                                                                solutions if they are not viable.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: How do backtracking algorithms work?</strong>
                                                            <p>A2: Backtracking algorithms explore all possible options
                                                                by exploring a tree of choices, backtracking when a
                                                                choice leads to an infeasible solution.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What are some common problems solved using
                                                                backtracking algorithms?</strong>
                                                            <p>A3: Common problems include the N-Queens problem, Sudoku,
                                                                and the subset sum problem.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: What is the N-Queens problem?</strong>
                                                            <p>A4: The N-Queens problem involves placing N queens on an
                                                                N×N chessboard so that no two queens attack each other.
                                                            </p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: How is Sudoku solved using backtracking
                                                                algorithms?</strong>
                                                            <p>A5: Sudoku is solved by filling in the grid incrementally
                                                                and backtracking whenever a number violates the Sudoku
                                                                rules.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: What is the subset sum problem?</strong>
                                                            <p>A6: The subset sum problem involves finding a subset of a
                                                                given set of integers that sum up to a specified value.
                                                            </p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What are the limitations of backtracking
                                                                algorithms?</strong>
                                                            <p>A7: Limitations include potentially high time complexity
                                                                due to exploring all possible solutions and not being
                                                                suitable for large problems without optimization
                                                                techniques.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: How can backtracking be optimized?</strong>
                                                            <p>A8: Optimizations include pruning branches that cannot
                                                                lead to a solution, using memoization, and incorporating
                                                                heuristic methods.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: How do you determine if a problem can be solved
                                                                with a backtracking algorithm?</strong>
                                                            <p>A9: A problem can be solved with backtracking if it can
                                                                be broken down into incremental steps with the
                                                                possibility of abandoning non-viable paths.</p>
                                                        </div>
