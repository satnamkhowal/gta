                                            <div id="collapseNine" class="collapse show" aria-labelledby="headingNine"
                                                data-parent="#accordion">
                                                <div class="card-body acc-content current">
                                                    <div class="container">
                                                        <div class="row">
                                                            <strong>Q1: What is dynamic programming?</strong>
                                                            <p>A1: Dynamic programming is an algorithmic technique for
                                                                solving problems by breaking them down into simpler
                                                                subproblems and storing the solutions to avoid redundant
                                                                calculations.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: What are the key principles of dynamic
                                                                programming?</strong>
                                                            <p>A2: Key principles include optimal substructure and
                                                                overlapping subproblems.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What is the difference between memoization and
                                                                tabulation?</strong>
                                                            <p>A3: Memoization is a top-down approach that stores
                                                                solutions to subproblems, while tabulation is a
                                                                bottom-up approach that builds solutions iteratively.
                                                            </p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: How does dynamic programming improve algorithm
                                                                efficiency?</strong>
                                                            <p>A4: By storing solutions to subproblems, dynamic
                                                                programming avoids redundant computations, reducing time
                                                                complexity.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What are some common problems solved using
                                                                dynamic programming?</strong>
                                                            <p>A5: Common problems include the Fibonacci sequence,
                                                                knapsack problem, and shortest path algorithms.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: What is the knapsack problem?</strong>
                                                            <p>A6: The knapsack problem involves selecting items with
                                                                given weights and values to maximize the total value
                                                                without exceeding a weight limit.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: How is dynamic programming used in the Fibonacci
                                                                sequence?</strong>
                                                            <p>A7: Dynamic programming stores the results of previous
                                                                Fibonacci calculations, reducing the exponential time
                                                                complexity to linear.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: What is the principle of optimality?</strong>
                                                            <p>A8: The principle of optimality states that the optimal
                                                                solution to a problem can be constructed from optimal
                                                                solutions to its subproblems.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: What are some limitations of dynamic
                                                                programming?</strong>
                                                            <p>A9: Limitations include high memory usage and difficulty
                                                                in identifying overlapping subproblems and optimal
                                                                substructure for some problems.</p>
                                                        </div>
