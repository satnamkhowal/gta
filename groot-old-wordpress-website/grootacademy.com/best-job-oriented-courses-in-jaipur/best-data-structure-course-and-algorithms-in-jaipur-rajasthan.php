                                                            <strong>Q5: What are the time complexities of common sorting
                                                                algorithms?</strong>
                                                            <p>A5: Time complexities include O(n log n) for quicksort
                                                                and merge sort, O(n^2) for bubble sort, and O(n) for
                                                                counting sort.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: What is the difference between stable and
                                                                unstable sorting algorithms?</strong>
                                                            <p>A6: Stable sorting algorithms preserve the relative order
                                                                of equal elements, while unstable algorithms do not.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What are in-place sorting algorithms?</strong>
                                                            <p>A7: In-place sorting algorithms sort the array without
                                                                requiring additional storage space proportional to the
                                                                input size.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: How do you choose the right sorting algorithm
                                                                for a problem?</strong>
                                                            <p>A8: The choice depends on factors like input size, time
                                                                complexity, space complexity, stability, and whether the
                                                                data is partially sorted.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: What are some real-world applications of sorting
                                                                algorithms?</strong>
                                                            <p>A9: Applications include organizing data (e.g.,
                                                                databases, spreadsheets), search optimization, and
                                                                improving the efficiency of other algorithms.</p>
                                                        </div>
