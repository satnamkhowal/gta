                                                        <div class="row">
                                                            <strong>Q1: What is hashing?</strong>
                                                            <p>A1: Hashing is the process of converting an input into a
                                                                fixed-size string of characters, which is typically a
                                                                hash code.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: What is a hash function?</strong>
                                                            <p>A2: A hash function is a function that takes input data
                                                                (keys) and returns a fixed-size value, which is the hash
                                                                code.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What are the properties of a good hash
                                                                function?</strong>
                                                            <p>A3: Properties include determinism, uniform distribution,
                                                                defined range, and efficiency.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: What is a hash table?</strong>
                                                            <p>A4: A hash table is a data structure that uses a hash
                                                                function to map keys to values, allowing for efficient
                                                                data retrieval.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What is collision in hashing, and how is it
                                                                handled?</strong>
                                                            <p>A5: A collision occurs when two keys hash to the same
                                                                index. It can be handled using techniques like chaining
                                                                and open addressing.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: What are some applications of hashing?</strong>
                                                            <p>A6: Applications include implementing associative arrays,
                                                                database indexing, and cryptographic algorithms.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What are the advantages of using hash
                                                                tables?</strong>
                                                            <p>A7: Advantages include fast data retrieval and insertion,
                                                                and efficient use of memory for large datasets.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: What is rehashing?</strong>
                                                            <p>A8: Rehashing is the process of resizing a hash table and
                                                                computing new hash codes for existing keys, typically to
                                                                reduce collisions and maintain performance.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: How do hash functions contribute to
                                                                security?</strong>
                                                            <p>A9: In cryptography, hash functions are used to ensure
                                                                data integrity, create digital signatures, and store
                                                                passwords securely.</p>
                                                        </div>
