                                                        <div class="row">
                                                            <strong>Q1: What is complexity analysis?</strong>
                                                            <p>A1: Complexity analysis evaluates the efficiency of
                                                                algorithms in terms of time and space usage.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: What are the types of complexities in
                                                                algorithms?</strong>
                                                            <p>A2: Types include time complexity and space complexity.
                                                            </p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What is time complexity?</strong>
                                                            <p>A3: Time complexity measures the amount of time an
                                                                algorithm takes to complete as a function of the input
                                                                size.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: What is space complexity?</strong>
                                                            <p>A4: Space complexity measures the amount of memory an
                                                                algorithm uses as a function of the input size.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What are Big O, Big Theta, and Big Omega
