                                                        <div class="row">
                                                            <strong>Q2: What are the types of searching
                                                                algorithms?</strong>
                                                            <p>A2: Types include linear search and binary search.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: How does linear search work?</strong>
                                                            <p>A3: Linear search sequentially checks each element of the
                                                                list until the target element is found or the list ends.
                                                            </p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: How does binary search work?</strong>
                                                            <p>A4: Binary search repeatedly divides the sorted list in
                                                                half, comparing the target value to the middle element,
                                                                until the target is found or the search interval is
                                                                empty.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What are the time complexities of common
                                                                searching algorithms?</strong>
                                                            <p>A5: Time complexities include O(n) for linear search and
                                                                O(log n) for binary search.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: What are some real-world applications of
                                                                searching algorithms?</strong>
