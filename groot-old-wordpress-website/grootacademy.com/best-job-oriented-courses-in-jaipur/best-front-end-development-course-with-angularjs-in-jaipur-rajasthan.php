                                                                `maxLength`, `pattern`), custom validator functions
                                                                (`Validators` class), and `FormGroup`/`FormControl`
                                                                instances. You define validation rules, apply error
                                                                messages (`FormGroup.errors`, `FormControl.errors`),
                                                                handle form control states, and use template-driven or
