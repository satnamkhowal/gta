                                                            <p>A3: Redux is set up by installing the library, creating a store with `createStore`, defining reducers, and using the `Provider` component to pass the store to the application.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: What is a reducer in Redux?</strong>
                                                            <p>A4: A reducer is a pure function that takes the current state and an action, and returns a new state based on the action type and payload.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What is an action in Redux?</strong>
                                                            <p>A5: An action is a plain JavaScript object that describes a change to be made to the state. It typically has a `type` property and may include a payload.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: How do you dispatch actions in Redux?</strong>
                                                            <p>A6: Actions are dispatched using the `dispatch` function provided by Redux, which sends actions to the store for processing by reducers.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What is the purpose of middleware in Redux?</strong>
                                                            <p>A7: Middleware provides a way to extend Redux functionality, such as handling asynchronous actions or logging state changes, before they reach reducers.</p>
