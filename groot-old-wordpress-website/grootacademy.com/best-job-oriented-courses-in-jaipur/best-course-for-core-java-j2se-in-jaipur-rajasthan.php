                                                                <p>The JDK (Java Development Kit) includes tools for
                                                                    developing Java applications, such as the compiler
                                                                    and debugger. The JRE (Java Runtime Environment)
                                                                    includes only the tools and libraries needed to run
                                                                    Java applications, without development tools.</p>
