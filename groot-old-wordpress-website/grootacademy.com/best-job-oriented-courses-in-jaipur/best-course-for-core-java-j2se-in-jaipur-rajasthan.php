                                                                <h5>1. What is JDBC?</h5>
                                                                <p>JDBC (Java Database Connectivity) is an API that
                                                                    allows Java applications to interact with databases.
                                                                    It provides methods for querying and updating data
                                                                    in a database.</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>2. What are the main components of JDBC?</h5>
                                                                <p>The main components of JDBC include DriverManager,
                                                                    Driver, Connection, Statement, and ResultSet.</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>3. How do you establish a database connection using
                                                                    JDBC?</h5>
                                                                <p>To establish a database connection using JDBC, you
                                                                    load the JDBC driver using
                                                                    Class.forName("driverClassName") and then create a
                                                                    connection object using
                                                                    DriverManager.getConnection(url, username,
                                                                    password).</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>4. What are the different types of JDBC drivers?
                                                                </h5>
                                                                <p>JDBC drivers are categorized into four types: Type 1
                                                                    (JDBC-ODBC bridge driver), Type 2 (Native-API
                                                                    driver), Type 3 (Network Protocol driver), and Type
                                                                    4 (Thin driver).</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>5. How do you execute SQL queries using JDBC?</h5>
                                                                <p>To execute SQL queries using JDBC, you create a
                                                                    Statement object using Connection.createStatement()
                                                                    and then use Statement.executeQuery(sql) for SELECT
                                                                    queries or Statement.executeUpdate(sql) for INSERT,
                                                                    UPDATE, DELETE queries.</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>6. What is PreparedStatement in JDBC?</h5>
                                                                <p>PreparedStatement in JDBC is a precompiled SQL
                                                                    statement that allows efficient execution of SQL
                                                                    queries with parameters.</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>7. How do you handle transactions in JDBC?</h5>
                                                                <p>Transactions in JDBC are handled using methods like
                                                                    Connection.setAutoCommit(false),
                                                                    Connection.commit(), and Connection.rollback().</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>8. What is ResultSet in JDBC?</h5>
                                                                <p>ResultSet in JDBC is an object that represents a set
                                                                    of rows retrieved from a database after executing a
                                                                    query.</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>9. How do you handle exceptions in JDBC?</h5>
                                                                <p>Exceptions in JDBC are typically handled using
                                                                    try-catch blocks. Common exceptions include
                                                                    SQLException and ClassNotFoundException.</p>
                                                            </div>

                                                            <div class="row">
                                                                <h5>10. Can JDBC be used for both relational and
                                                                    non-relational databases?</h5>
                                                                <p>JDBC is primarily designed for relational databases
                                                                    that support SQL.</p>
