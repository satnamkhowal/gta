                                                    <div class="container">
                                                        <!-- FAQs for Module 6 -->
                                                        <div class="row">
                                                            <strong>Q1: What is an array in Go?</strong>
                                                            <p>A1: An array is a fixed-size, ordered collection of
                                                                elements of the same type. It is declared with a
                                                                specific size and type.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: How do you declare an array in Go?</strong>
                                                            <p>A2: An array is declared using the syntax `var arr
                                                                [size]type`, where `size` is the number of elements and
                                                                `type` is the data type.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What is a slice in Go?</strong>
                                                            <p>A3: A slice is a dynamically-sized, flexible view into
                                                                the elements of an array. It is more powerful and
                                                                convenient than an array.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: How do you create a slice in Go?</strong>
                                                            <p>A4: A slice can be created by slicing an array, using the
                                                                `make` function, or by using a slice literal.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What is the difference between an array and a
                                                                slice?</strong>
                                                            <p>A5: An array has a fixed size and cannot be resized,
                                                                while a slice is a reference type that can grow and
                                                                shrink as needed.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: How do you append elements to a slice?</strong>
                                                            <p>A6: Elements are appended to a slice using the built-in
                                                                `append` function, which adds new elements and returns
                                                                the updated slice.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What is a map in Go?</strong>
                                                            <p>A7: A map is an unordered collection of key-value pairs,
                                                                where each key is unique. It is used for fast data
                                                                retrieval based on keys.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: How do you create a map in Go?</strong>
                                                            <p>A8: A map is created using the `make` function or a map
                                                                literal. The syntax is `make(map[keyType]valueType)` or
                                                                `map[keyType]valueType{}`.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: How do you access and modify map
                                                                elements?</strong>
                                                            <p>A9: Map elements are accessed and modified using the
                                                                syntax `map[key]`, where `key` is the key whose value
                                                                you want to retrieve or update.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q10: How do you check if a key exists in a
                                                                map?</strong>
                                                            <p>A10: You can check if a key exists in a map by using the
                                                                value, ok idiom: `value, ok := map[key]`. If `ok` is
                                                                true, the key exists.</p>
