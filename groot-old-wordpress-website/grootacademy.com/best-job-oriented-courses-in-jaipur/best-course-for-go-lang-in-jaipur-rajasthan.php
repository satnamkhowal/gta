                                                            <p>A1: A struct is a composite data type that groups
                                                                together variables under a single name. These variables
                                                                are called fields.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: How do you define a struct in Go?</strong>
                                                            <p>A2: A struct is defined using the `type` keyword followed
                                                                by the struct name and the `struct` keyword, with fields
                                                                defined within curly braces.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: How do you create an instance of a
                                                                struct?</strong>
                                                            <p>A3: An instance of a struct can be created using a struct
                                                                literal, the `new` keyword, or by declaring a variable
                                                                of the struct type.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: How do you access and modify struct
                                                                fields?</strong>
                                                            <p>A4: Struct fields are accessed and modified using the dot
                                                                notation: `structInstance.fieldName`.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What are methods in Go?</strong>
                                                            <p>A5: Methods are functions with a special receiver
                                                                argument. They are used to define behavior for structs
                                                                and other types.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: How do you define a method for a
                                                                struct?</strong>
                                                            <p>A6: A method is defined by specifying a receiver argument
                                                                in the function definition. The receiver can be a value
                                                                or a pointer to the struct.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What is the difference between value and pointer
                                                                receivers?</strong>
                                                            <p>A7: Value receivers operate on a copy of the original
                                                                struct, while pointer receivers operate on the actual
                                                                struct, allowing modification of its fields.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: Can you define methods for non-struct
                                                                types?</strong>
                                                            <p>A8: Yes, methods can be defined for any named type,
                                                                including built-in types, as long as the receiver is
                                                                specified.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: How do you embed structs in Go?</strong>
                                                            <p>A9: Struct embedding allows you to include one struct
                                                                within another, providing a way to extend and reuse
                                                                fields and methods.</p>
                                                        </div>
