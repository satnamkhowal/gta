                                                        <!-- FAQs for Module 8 -->
                                                        <div class="row">
                                                            <strong>Q1: What is concurrency in Go?</strong>
                                                            <p>A1: Concurrency in Go is the ability to run multiple
                                                                tasks or functions simultaneously, making use of Go's
                                                                goroutines and channels.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q2: What is a goroutine?</strong>
                                                            <p>A2: A goroutine is a lightweight thread managed by the Go
                                                                runtime. It is created using the `go` keyword followed
                                                                by a function call.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: How do you create a goroutine?</strong>
                                                            <p>A3: A goroutine is created by prefixing a function call
                                                                with the `go` keyword, which runs the function
                                                                concurrently.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: What is a channel in Go?</strong>
                                                            <p>A4: A channel is a conduit for sending and receiving
                                                                values between goroutines. It is created using the
                                                                `make` function.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: How do you send and receive values through a
                                                                channel?</strong>
                                                            <p>A5: Values are sent to a channel using the `chan <-`
                                                                    syntax and received from a channel using the `<-
                                                                    chan` syntax.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: What is a buffered channel?</strong>
                                                            <p>A6: A buffered channel has a capacity, allowing it to
                                                                store multiple values before blocking. It is created by
                                                                passing a buffer size to the `make` function.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: How do you close a channel in Go?</strong>
                                                            <p>A7: A channel is closed using the `close` function, which
                                                                signals that no more values will be sent on the channel.
                                                            </p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: What is the select statement in Go?</strong>
                                                            <p>A8: The select statement allows a goroutine to wait on
                                                                multiple communication operations, executing the case
                                                                for the first operation that is ready.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: How do you handle timeouts in Go?</strong>
                                                            <p>A9: Timeouts are handled using the `time.After` function
                                                                in combination with the select statement to wait for a
                                                                specified duration.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q10: What are worker pools in Go?</strong>
                                                            <p>A10: Worker pools are a concurrency pattern where a fixed
                                                                number of goroutines (workers) process tasks from a
                                                                channel, allowing for efficient resource usage.</p>
                                                        </div>
