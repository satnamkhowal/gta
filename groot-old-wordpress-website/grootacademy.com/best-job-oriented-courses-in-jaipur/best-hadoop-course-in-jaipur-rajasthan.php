                                                            <strong>Q2: What is Pig Latin?</strong>
                                                            <p>A2: Pig Latin is a scripting language used in Apache Pig to write data processing tasks, similar to SQL but designed for large-scale data processing.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: How does Pig differ from Hive?</strong>
