                                                            <p>A2: Hive uses a schema-on-read approach, where the schema is applied to the data when it is read, rather than when it is written.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What are Hive tables?</strong>
                                                            <p>A3: Hive tables are structures that organize data in a format similar to relational databases, allowing for querying and management using HiveQL.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: How do you perform data querying in Hive?</strong>
                                                            <p>A4: Data querying in Hive is performed using HiveQL, which is similar to SQL and allows for complex queries, joins, and aggregations.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What is a Hive partition?</strong>
                                                            <p>A5: A Hive partition is a way to divide a table into smaller, more manageable pieces based on a specific column’s value, improving query performance.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: How does Hive optimize query performance?</strong>
                                                            <p>A6: Hive optimizes query performance through techniques such as indexing, partitioning, and bucketing.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What is the role of Hive Metastore?</strong>
                                                            <p>A7: The Hive Metastore stores metadata about Hive tables, schemas, and partitions, enabling efficient data management and querying.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: How do you handle data transformation in Hive?</strong>
                                                            <p>A8: Data transformation in Hive is handled using HiveQL functions and operations to convert data into the desired format or structure.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: What are some common use cases for Hive?</strong>
                                                            <p>A9: Common use cases include data warehousing, data analysis, business intelligence, and reporting on large datasets.</p>
