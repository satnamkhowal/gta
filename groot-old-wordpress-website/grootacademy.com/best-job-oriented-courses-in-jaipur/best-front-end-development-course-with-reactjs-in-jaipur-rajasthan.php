                                                                React?</strong>
                                                            <p>A3: Unit testing in React can be performed using testing
                                                                libraries like Jest and testing utilities like React
                                                                Testing Library or Enzyme. Tests focus on verifying
                                                                component rendering, state changes, and behavior using
                                                                assertions and mock data.</p>
                                                        </div>

                                                        <div class="row">
                                                            <strong>Q4: What are the benefits of using Jest for testing
                                                                React applications?</strong>
                                                            <p>A4: Jest is a popular testing framework for React
                                                                applications due to its ease of setup, built-in
                                                                assertions, snapshot testing for UI components, mocking
                                                                capabilities for dependencies, parallel test execution,
                                                                and integration with tools like React Testing Library.
                                                            </p>
                                                        </div>

                                                        <div class="row">
                                                            <strong>Q5: How do you write snapshot tests in
                                                                Jest?</strong>
                                                            <p>A5: Snapshot testing in Jest involves capturing the
                                                                rendered output of a React component and saving it as a
                                                                serialized snapshot file. Subsequent tests compare the
                                                                current component output with the saved snapshot to
                                                                detect unexpected changes in UI rendering.</p>
                                                        </div>

                                                        <div class="row">
                                                            <strong>Q6: What is mocking in testing React
                                                                applications?</strong>
                                                            <p>A6: Mocking in testing React applications involves
                                                                replacing dependencies with simulated objects or
                                                                functions that mimic the behavior of real components or
                                                                APIs. It allows you to isolate components for testing
                                                                without relying on external resources.</p>
                                                        </div>

                                                        <div class="row">
                                                            <strong>Q7: How do you handle asynchronous code in Jest
                                                                tests?</strong>
                                                            <p>A7: Asynchronous code in Jest tests can be handled using
                                                                async/await syntax for promises, `done` callback for
                                                                callbacks, or Jest's `waitFor` utility with `act` for
                                                                handling asynchronous updates in React components.</p>
                                                        </div>

