                                                            <strong>Q2: What are the types of testing used in
                                                                React?</strong>
                                                            <p>A2: Types of testing used in React include:
                                                            <ul>
                                                                <li><strong>Unit testing:</strong> Testing individual
                                                                    units or components in isolation to verify
                                                                    correctness.</li>
                                                                <li><strong>Integration testing:</strong> Testing
                                                                    interactions between components or modules to ensure
                                                                    they work together.</li>
                                                                <li><strong>End-to-end (E2E) testing:</strong> Testing
                                                                    entire workflows from start to finish to simulate
                                                                    real user scenarios.</li>
                                                            </ul>
                                                            </p>
