                                                                    of your whole application is stored in an object
                                                                    tree within a single store.</li>
                                                                <li><strong>State is read-only:</strong> The only way to
                                                                    change the state is to emit an action, an object
                                                                    describing what happened.</li>
                                                                <li><strong>Changes are made with pure
