                                                        <div class="row">
                                                            <strong>Q2: How does JPA handle entity inheritance?</strong>
                                                            <p>A2: JPA supports inheritance through strategies like `SINGLE_TABLE`, `JOINED`, and `TABLE_PER_CLASS`, allowing for polymorphic entity relationships.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q3: What are entity listeners in JPA?</strong>
                                                            <p>A3: Entity listeners are callback methods that respond to lifecycle events of entities, such as pre-persist or post-load operations.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q4: How do you use custom converters in JPA?</strong>
                                                            <p>A4: Custom converters are used to define how Java types are converted to database column types and vice versa, using the `@Converter` annotation.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q5: What is the role of `@PostLoad` annotation?</strong>
                                                            <p>A5: The `@PostLoad` annotation marks a method to be called after an entity is loaded from the database, allowing for post-processing.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q6: How does JPA implement caching?</strong>
                                                            <p>A6: JPA implements caching with first-level (persistence context) and second-level (shared cache) caches to enhance performance and reduce database access.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q7: What is the purpose of `@Cache` annotation?</strong>
                                                            <p>A7: The `@Cache` annotation is used to configure entity caching strategies and policies, such as read-only or read-write caching.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q8: How can you customize JPA query execution?</strong>
                                                            <p>A8: Customize query execution using hints, custom query execution strategies, and by extending `Query` or `TypedQuery` interfaces.</p>
                                                        </div>
                                                        <div class="row">
                                                            <strong>Q9: What is the use of `@SqlResultSetMapping`?</strong>
                                                            <p>A9: `@SqlResultSetMapping` is used to map the results of native SQL queries to entity classes or DTOs, allowing custom result mappings.</p>
